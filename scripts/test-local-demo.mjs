import assert from 'node:assert/strict';
import { build } from 'esbuild';

const values = new Map();
globalThis.localStorage = { getItem: key => values.get(key) ?? null, setItem: (key, value) => values.set(key, value) };
globalThis.window = new EventTarget();
const bundled = await build({ entryPoints: ['src/lib/data.ts'], bundle: true, write: false, format: 'esm', platform: 'browser', define: { 'import.meta.env': JSON.stringify({ DEV: true, VITE_LOCAL_DEMO: 'true' }) } });
const data = await import(`data:text/javascript;base64,${Buffer.from(bundled.outputFiles[0].text).toString('base64')}`);
const db = {};
const users = await data.getDocs(data.collection(db, 'users'));
assert.equal(users.size, 7);
assert.equal(new Set(users.docs.map(user => user.data().role)).size, 7);
const machine = data.doc(db, 'planters', 'TEST-001');
await data.setDoc(machine, { id: 'TEST-001', lastReading: 0, gallery: [], approvals: {} });
await data.updateDoc(machine, { lastReading: data.increment(100), gallery: data.arrayUnion('image', 'image'), 'approvals.areaManager': { approved: true } });
assert.equal((await data.getDoc(machine)).data().lastReading, 100);
assert.deepEqual((await data.getDoc(machine)).data().approvals, { areaManager: { approved: true } });
await data.updateDoc(machine, { gallery: data.arrayUnion('image') });
assert.equal((await data.getDoc(machine)).data().gallery.length, 1);
await data.setDoc(machine, { brand: 'Demo' }, { merge: true });
assert.equal((await data.getDoc(machine)).data().lastReading, 100);
await data.addDoc(data.collection(machine, 'usageLogs'), { type: 'reading', timestamp: '2026-10-26' });
assert.equal((await data.getDocs(data.collection(db, 'planters'))).size, 19);
assert.equal((await data.getDocs(data.collection(machine, 'usageLogs'))).size, 1);
const filtered = await data.getDocs(data.query(data.collection(db, 'planters'), data.where('lastReading', '>=', 100), data.orderBy('lastReading', 'desc'), data.limit(2)));
assert.equal(filtered.size, 2);
assert.ok(filtered.docs[0].data().lastReading >= filtered.docs[1].data().lastReading);
let emissions = 0;
const unsubscribe = data.onSnapshot(machine, () => emissions++);
await new Promise(resolve => queueMicrotask(resolve));
await data.updateDoc(machine, { lastReading: 200 });
assert.equal(emissions, 2);
unsubscribe();
await data.updateDoc(machine, { lastReading: 300 });
assert.equal(emissions, 2);
const batch = data.writeBatch(db);
batch.update(machine, { lastReading: 999 });
batch.update(data.doc(db, 'planters', 'missing'), { lastReading: 1 });
await assert.rejects(batch.commit());
assert.equal((await data.getDoc(machine)).data().lastReading, 300);
await data.deleteDoc(machine);
assert.equal((await data.getDoc(machine)).exists(), false);
assert.ok([...values.values()][0].includes('demo-admin'));
console.log('Local demo: seven roles, persistence, queries, transforms, subscriptions, nested records, merge, batch rollback and deletion passed.');
