import assert from 'node:assert/strict';
import { build } from 'esbuild';

const values = new Map();
globalThis.localStorage = { getItem: key => values.get(key) ?? null, setItem: (key, value) => values.set(key, value) };
globalThis.window = new EventTarget();
window.location = { origin: 'http://localhost:3001' };
const bundled = await build({ stdin: { contents: "export * from './src/lib/fieldOperations'; export * as data from './src/lib/data'; export { demoUsers } from './src/lib/demo';", resolveDir: process.cwd(), loader: 'ts' }, bundle: true, write: false, format: 'esm', platform: 'browser', define: { 'import.meta.env': JSON.stringify({ DEV: true, VITE_LOCAL_DEMO: 'true' }) } });
const { data, demoUsers, ...workflow } = await import(`data:text/javascript;base64,${Buffer.from(bundled.outputFiles[0].text).toString('base64')}`);
const [admin, state, district, area, cf, jcf] = demoUsers;
const db = {};
assert.equal(workflow.parseQRIdentifier('http://localhost:3001/scan/QR-2026-TEST-001?source=label#usage'), 'QR-2026-TEST-001');
assert.equal(workflow.parseQRIdentifier('/scan/QR-2026-TEST-001'), 'QR-2026-TEST-001');
assert.equal(workflow.parseQRIdentifier('https://example.test/?id=QR-2026-TEST-001'), 'QR-2026-TEST-001');
assert.throws(() => workflow.parseQRIdentifier('javascript:alert(1)'));

const before = (await data.getDocs(data.collection(db, 'planters'))).size;
const batch = await workflow.createQRBatch(admin, '100 general labels', 100);
let labels = (await data.getDocs(data.collection(db, 'qr_labels'))).docs.map(record => record.data());
assert.equal(labels.length, 100);
assert.equal(new Set(labels.map(label => label.id)).size, 100);
assert.equal((await data.getDocs(data.collection(db, 'planters'))).size, before, 'Generation must not create machines');
assert.ok(labels.every(label => !label.machineType && label.status === 'available'));
await assert.rejects(workflow.createQRBatch(area, 'Not allowed', 100));
await assert.rejects(workflow.createQRBatch(admin, 'Invalid', 0));
const ids = labels.slice(0, 50).map(label => label.id);
await workflow.distributeQRLabels(admin, ids, district.uid);
await assert.rejects(workflow.distributeQRLabels(admin, ids, district.uid), 'Old holder cannot redistribute labels');
await assert.rejects(workflow.distributeQRLabels(district, ids, cf.uid), 'Cannot skip area manager');
await workflow.distributeQRLabels(district, ids.slice(0, 25), area.uid);
const location = { state: 'Telangana', district: 'Nizamabad', mandal: 'Armoor', village: 'Demo village', lat: 18.79, lng: 78.28 };
const details = { ...location, machineType: 'MCP', brand: 'Demo brand', model: '2026', serialNumber: 'SN-TEST', cfId: cf.uid, photos: [] };
await assert.rejects(workflow.onboardFieldMachine(district, ids[0], details));
await assert.rejects(workflow.onboardFieldMachine(area, ids[30], details), 'Undistributed label cannot be attached');
const outsider = { uid: 'outside-cf', email: 'outside@demo.local', displayName: 'Other branch CF', role: 'cf', parentId: district.uid };
await data.setDoc(data.doc(db, 'users', outsider.uid), outsider);
await assert.rejects(workflow.onboardFieldMachine(area, ids[0], { ...details, cfId: outsider.uid }), 'Cannot assign a CF outside the area branch');
const machine = await workflow.onboardFieldMachine(area, ids[0], details);
assert.equal(machine.currentHolderId, cf.uid);
assert.equal((await data.getDoc(data.doc(db, 'qr_labels', ids[0]))).data().status, 'attached');
await assert.rejects(workflow.onboardFieldMachine(area, ids[0], details), 'A QR can only onboard one machine');
await assert.rejects(workflow.distributeQRLabels(area, [ids[0]], cf.uid), 'Attached labels cannot be redistributed');
const farmerDetails = { ...location, name: 'Lead Farmer', phone: '9876543210', landAcres: 5, photos: ['data:image/png;base64,demo'] };
await assert.rejects(workflow.onboardLeadFarmer(cf, machine.id, { ...farmerDetails, photos: [] }));
const farmer = await workflow.onboardLeadFarmer(cf, machine.id, farmerDetails);
await assert.rejects(workflow.onboardLeadFarmer(cf, machine.id, farmerDetails), 'Cannot silently replace lead farmer');
const usageDetails = { ...location, farmerKind: 'fellow', farmerName: 'Fellow Farmer', phone: '9876501234', crop: 'Paddy', landAcres: 2.5, operationDate: new Date().toLocaleDateString('en-CA'), photos: ['data:image/png;base64,field'], notes: 'Sowing completed' };
await assert.rejects(workflow.recordFarmerUsage(district, machine.id, usageDetails));
await assert.rejects(workflow.recordFarmerUsage(cf, machine.id, { ...usageDetails, landAcres: -1 }));
await assert.rejects(workflow.recordFarmerUsage(cf, machine.id, { ...usageDetails, photos: [] }));
await assert.rejects(workflow.recordFarmerUsage(outsider, machine.id, usageDetails), 'Other branch CF cannot record usage');
await assert.rejects(workflow.recordFarmerUsage(cf, machine.id, { ...usageDetails, operationDate: 'not-a-date' }));
const usage = await workflow.recordFarmerUsage(jcf, machine.id, usageDetails);
assert.equal(usage.recordedBy, jcf.uid, 'Assigned CF’s JCF can record work');
const after = (await data.getDoc(data.doc(db, 'planters', machine.id))).data();
assert.equal(after.currentCustodian, farmer.name, 'Fellow usage must not replace lead farmer custody');
assert.equal(after.currentHolderId, cf.uid, 'Fellow usage must not replace CF responsibility');
assert.equal(after.leadFarmerId, farmer.id);
assert.equal((await data.getDocs(data.collection(db, 'field_usage'))).size, 1);
assert.equal((await data.getDocs(data.collection(db, 'planters', machine.id, 'usageLogs'))).size, 2);
assert.equal((await data.getDoc(data.doc(db, 'updates', usage.id))).data().areaAcres, 2.5);
assert.equal((await data.getDocs(data.collection(db, 'qr_transfers'))).size, 2);
console.log('Field workflow passed: 100 general QR labels → district → area → machine + CF → lead farmer → JCF records fellow usage. Ownership, proof, role and duplicate guards passed.');
