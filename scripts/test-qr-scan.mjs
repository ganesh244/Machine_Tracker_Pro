import assert from 'node:assert/strict';
import { build } from 'esbuild';
import QRCode from 'qrcode';
import { PNG } from 'pngjs';
const bundle = await build({ entryPoints: ['src/lib/qrScan.ts'], bundle: true, write: false, format: 'esm', platform: 'node' });
const { decodeQRImage } = await import(`data:text/javascript;base64,${Buffer.from(bundle.outputFiles[0].text).toString('base64')}`);
const url = 'http://localhost:3001/scan/DEMO-QR-001';
const bytes = await QRCode.toBuffer(url, { width: 600, margin: 4 });
const image = PNG.sync.read(bytes);
assert.equal(decodeQRImage(new Uint8ClampedArray(image.data), image.width, image.height), url);
const rotated = new Uint8ClampedArray(image.data.length);
for(let y=0;y<image.height;y++) for(let x=0;x<image.width;x++) for(let c=0;c<4;c++) rotated[((x*image.width)+(image.width-1-y))*4+c]=image.data[(y*image.width+x)*4+c];
assert.equal(decodeQRImage(rotated, image.width, image.height), url);
const inverted = new Uint8ClampedArray(image.data);
for(let n=0;n<inverted.length;n++) if(n%4!==3) inverted[n]=255-inverted[n];
assert.equal(decodeQRImage(inverted, image.width, image.height), url);
assert.equal(decodeQRImage(new Uint8ClampedArray(100*100*4).fill(255),100,100), null);
await QRCode.toFile('/private/tmp/farmmech-demo-qr-onboard.png', url, { width: 600, margin: 4 });
console.log('QR pixel decoding passed: generated PNG, rotated QR, inverted QR, blank image rejection. Browser upload fixture: /private/tmp/farmmech-demo-qr-onboard.png');
