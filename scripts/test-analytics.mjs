import assert from 'node:assert/strict';
import { build } from 'esbuild';

const values = new Map();
globalThis.localStorage = { getItem: key => values.get(key) ?? null, setItem: (key, value) => values.set(key, value) };
globalThis.window = new EventTarget();
window.location = { origin: 'http://localhost:3001' };
const bundled = await build({ stdin: { contents: "export * from './src/lib/demoScenarios'; export * from './src/lib/analytics'; export * from './src/lib/fieldOperations'; export * as data from './src/lib/data'; export { demoUsers } from './src/lib/demo';", resolveDir: process.cwd(), loader: 'ts' }, bundle: true, write: false, format: 'esm', platform: 'browser', define: { 'import.meta.env': JSON.stringify({ DEV: true, VITE_LOCAL_DEMO: 'true' }) } });
const { data, demoUsers, ...workflow } = await import(`data:text/javascript;base64,${Buffer.from(bundled.outputFiles[0].text).toString('base64')}`);
await workflow.ensureDemoScenarios();
const users = demoUsers;
const machines = (await data.getDocs(data.collection({}, 'planters'))).docs.map(d=>d.data()).filter(d=>d.qrLabelId);
const usage = (await data.getDocs(data.collection({}, 'field_usage'))).docs.map(d=>d.data());
for (const actor of users) {
 const result = workflow.buildAnalytics(actor, users, machines, usage);
 assert.equal(result.machines.length,12, actor.role);
 assert.equal(result.totalAcres,45);
 assert.equal(result.visits,15);
 assert.equal(result.machineTypes.length,3);
 assert.ok(result.machineTypes.every(type=>type.total===4));
 assert.equal(result.machineTypes.reduce((sum,type)=>sum+type.acres,0),45);
 assert.ok(result.machineTypes.every(type=>type.running+type.idle+type.maintenance===type.total));
 assert.equal(result.running + result.idle + result.maintenance,12);
 assert.equal(result.maintenance,6);
 assert.equal(result.topMachines.length,5);
 assert.equal(result.topMachines[0].acres,9);
 assert.equal(result.crops.length,3);
 assert.equal(result.crops.reduce((sum,row)=>sum+row.acres,0),result.totalAcres);
}
const outsider = { uid:'other-state', role:'state_manager', displayName:'Other state' };
assert.equal(workflow.buildAnalytics(outsider,[...users,outsider],machines,usage).totalAcres,0);
assert.equal(workflow.buildAnalytics(outsider,[...users,outsider],machines,usage).machines.length,0);
const day=usage[0].operationDate;
const filtered = workflow.buildAnalytics(users[4],users,machines,usage,day,day);
assert.equal(filtered.visits,5);
assert.equal(filtered.machineTypes.reduce((sum,type)=>sum+type.total,0),12);
assert.equal(filtered.machineTypes.reduce((sum,type)=>sum+type.acres,0),7.5);
assert.equal(workflow.machineTypeName({machineType:' drum  seeder '}),'Drum seeder');
assert.equal(workflow.machineTypeName({machineType:'Laser land leveler'}),'Laser land leveller');
assert.equal(workflow.machineTypeName({type:'Multicrop Planter'}),'MCP');
assert.equal(workflow.machineTypeName({machineType:'Rotavator'}),'Rotavator');
assert.equal(filtered.totalAcres,7.5);
assert.equal(filtered.machines.length,12,'date filter must not change current fleet counts');
assert.equal(workflow.buildAnalytics(users[4],users,machines,usage,'2099-01-01').totalAcres,0);
const mixed=[...usage,{...usage[0],id:'case-test',crop:' pAdDy ',landAcres:2},{...usage[0],id:'foreign',machineId:'not-in-scope',landAcres:999}];
const grouped=workflow.buildAnalytics(users[4],users,machines,mixed);
assert.equal(grouped.crops.length,3);
assert.equal(grouped.totalAcres,47);
assert.equal(workflow.defaultGeography('cf'),'village');
assert.equal(workflow.defaultGeography('area_manager'),'mandal');
assert.equal(workflow.defaultGeography('district_manager'),'district');
assert.equal(workflow.defaultGeography('farm_mechanization'),'state');
assert.equal(workflow.machineState({status:'in_use',operatingStatus:'maintenance'}),'Maintenance');
assert.equal(workflow.machineState({status:'in_use',operatingStatus:'operating'}),'Running');
console.log('Analytics passed: all 7 roles, branch isolation, acreage reconciliation, top five, crop normalization, date filters, empty data and exclusive fleet status counts.');
