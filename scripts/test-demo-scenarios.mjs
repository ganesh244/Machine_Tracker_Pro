import assert from 'node:assert/strict';
import { build } from 'esbuild';

const values = new Map();
globalThis.localStorage = { getItem: key => values.get(key) ?? null, setItem: (key, value) => values.set(key, value) };
globalThis.window = new EventTarget();
window.location = { origin: 'http://localhost:3001' };
const bundled = await build({ stdin: { contents: "export * from './src/lib/demoScenarios'; export * from './src/lib/fieldOperations'; export * as data from './src/lib/data'; export { demoUsers } from './src/lib/demo';", resolveDir: process.cwd(), loader: 'ts' }, bundle: true, write: false, format: 'esm', platform: 'browser', define: { 'import.meta.env': JSON.stringify({ DEV: true, VITE_LOCAL_DEMO: 'true' }) } });
const { data, demoUsers, ...workflow } = await import(`data:text/javascript;base64,${Buffer.from(bundled.outputFiles[0].text).toString('base64')}`);
const { ensureDemoScenarios, demoLabel } = workflow;
assert.equal(await ensureDemoScenarios(), true);
const count = async name => (await data.getDocs(data.collection({}, name))).size;
assert.equal(await count('qr_labels'), 100);
assert.equal(await count('planters'), 30);
assert.equal(await count('farmers'), 11);
assert.equal(await count('field_usage'), 15);
for (const n of [1, 11, 12, 15, 16, 17, 18, 19, 20, 21, 22]) assert.ok((await data.getDoc(data.doc({}, 'qr_labels', demoLabel(n)))).exists());
const reqs = (await data.getDocs(data.collection({}, 'maintenance_requests'))).docs.map(d => d.data()).filter(d => d.workflowVersion === 2);
assert.equal(reqs.length, 8);
assert.equal(new Set(reqs.map(d => d.status)).size, 8);
await data.updateDoc(data.doc({}, 'planters', demoLabel(12)), { model: 'USER EDIT PRESERVED' });
await ensureDemoScenarios();
assert.equal(await count('qr_labels'), 100);
assert.equal((await data.getDoc(data.doc({}, 'planters', demoLabel(12)))).data().model, 'USER EDIT PRESERVED');
const [admin, state, district, area, cf, jcf] = demoUsers;
const location = { state: 'Telangana', district: 'Nizamabad', mandal: 'Armoor', village: 'DEMO test', lat: 18.793, lng: 78.289 };
const machine = await workflow.onboardFieldMachine(area, demoLabel(1), { ...location, machineType: 'Drum seeder', brand: 'DEMO', model: 'Test', serialNumber: 'DEMO-test', cfId: cf.uid, photos: [workflow.DEMO_PHOTO] });
const farmer = await workflow.onboardLeadFarmer(cf, machine.id, { ...location, name: 'DEMO Test lead', phone: '0000000000', landAcres: 5, photos: [workflow.DEMO_PHOTO] });
await workflow.recordFarmerUsage(jcf, machine.id, { ...location, farmerKind: 'fellow', farmerName: 'DEMO Test fellow', phone: '0000000000', landAcres: 2, crop: 'Paddy', operationDate: new Date().toISOString().slice(0,10), photos: [workflow.DEMO_PHOTO], notes: 'Test' });
assert.equal((await data.getDoc(data.doc({}, 'planters', machine.id))).data().leadFarmerId, farmer.id);
console.log('Demo scenarios passed: 100 labels, 12 machines, 11 lead farmers, 15 usage visits, 8 maintenance stages; additive reload preserves edits; sample onboarding → farmer → JCF usage passed.');
